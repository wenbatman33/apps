function roadXV4(i, y) {
  const p = ROAD_PATHS_V4[i];
  if (y <= p[0][0]) return p[0][1];
  for (let k = 1; k < p.length; k++) {
    if (y <= p[k][0]) {
      const a = p[k-1], b = p[k];
      return a[1] + (b[1] - a[1]) * (y - a[0]) / (b[0] - a[0]);
    }
  }
  return p[p.length-1][1];
}
// 五路 x：0/2/4=土路，1/3=兩路中線草地
function laneXV4(lane, y) {
  if (lane === 0) return roadXV4(0, y);
  if (lane === 2) return roadXV4(1, y);
  if (lane === 4) return roadXV4(2, y);
  if (lane === 1) return (roadXV4(0, y) + roadXV4(1, y)) / 2;
  return (roadXV4(1, y) + roadXV4(2, y)) / 2;
}
