#!/bin/bash
# 把 LCD 原作整張精緻化成 Pixar 3D 風 — 一次性生整張，所有角色 pose 與原作完全對應
set -u
cd "$(dirname "$0")/.."

LOG="scripts/gen_lcd_remaster.log"
OUT="public/assets/lcd_remaster.png"
mkdir -p public/assets

ts() { date +"%H:%M:%S"; }
log() { echo "[$(ts)] $*" | tee -a "$LOG"; }

log "==== 精緻化 LCD 全景 ===="

PROMPT="附加圖是 Casio Western Bar 1984 LCD 原作的完整螢幕畫面。

任務：請用 image_gen 工具把這張 LCD 原作畫面【精緻化 / remaster】成 1536×1024 的彩色版本，
保留原作的整體 layout、各角色【pose】與【位置】，只是把黑白 LCD 線稿轉成 Pixar 3D 卡通可愛風。

【絕對嚴格 — 整張圖只能出現以下 5 種角色身份，不准添加任何其他人物】：

(A) 警長（主角）— **整張圖內所有警長必須是【完全同一人】，臉、年紀、體型、服裝 100% 一致**：
    - 五十多歲、瘦削、白色八字鬍（兩端翹起）、紅鼻頭
    - 米色寬邊 cowboy hat（一頂、款式固定）
    - 紅黑格紋襯衫 + 棕色皮背心 + 左胸金色五角星徽
    - 藍牛仔褲 + 棕色皮靴 + 腰間槍套
    - 警長在原作出現 5-7 次（不同 pose：站立 / 走路 / 持槍 / 開火 / 倒酒 / 中槍）
    - **每一次出現都是同一張臉、同一套衣服、同一個年紀**
    - 不准出現「白鬍年輕版」「棕鬍胖版」「無星徽版」等變體
    - 不准畫成「坐著喝酒的老爺爺」或任何休閒姿態

(B) 通緝犯 — **整張圖內所有通緝犯必須是【完全同一人】**：
    - 三十多歲、精瘦、黑色寬邊帽、紅色 bandana 蒙住下半臉
    - 髒灰白襯衫 + 棕色皮背心 + 胸前交叉子彈帶
    - 深褐色長褲 + 棕靴 + 腰間雙槍套
    - 出現多個 pose：站門口 / 進場 / 躲 / 刺探 / 開槍 / 中槍

(C) 酒保 — 1 人，金色背心、白襯衫、領結、站吧台最右

(D) 丈夫 — 1 人，中年絡腮鬍、藍格紋衫、吊帶褲，與妻子同坐中央圓桌

(E) 妻子 — 1 人，包頭髮髻、粉紅洋裝、白圍裙，與丈夫同坐中央圓桌

【嚴格禁止】：
- ✗ 不准添加任何「酒吧客人」「圍觀群眾」「其他牛仔」「老爺爺」「小孩」「狗」等多餘角色
- ✗ 不准把警長畫成多個不同人（白鬍老人 + 棕鬍胖子 = 錯誤，必須是同一人）
- ✗ 不准畫坐在椅子上喝酒倒酒的閒人 — 倒酒 pose 是警長在玩家走道上做的動作
- ✗ 不准加文字、編號、紅圈標記
- ✗ 不准加 LCD 邊框外的元素（按鈕、控制器、SCORE 顯示器）

【場景元件（依原作位置畫）】：
彈簧門（左牆）/ 吧台檯面（橫貫畫面中段）/ 酒瓶架（後牆）/ WANTED 海報 /
中央圓桌（夫婦坐）/ 椅子 / 木地板 / 杯/瓶/盤/蘋果/菸灰缸（吧台上）/
炸彈（地上 / 飛行中）/ 威士忌瓶（警長手上）

【風格】：Pixar / Mario Odyssey 3D Q版 chibi，3D 渲染、軟陰影、subsurface scattering、
明亮飽和色彩、圓潤無稜角、Q 版大頭比例、無線稿。
氣氛：西部酒吧黃昏暖光、木質溫暖色調、輕鬆幽默。

【輸出規範】：
- 1536×1024 PNG（橫向）
- 整張就是 LCD 螢幕內容，不要加邊框 / 機殼 / 按鈕
- 高細節可裁切 sprite

完成後存到 /Users/batman_work/claude/apps/westernBar/$OUT
並用 sips 確認尺寸 1536×1024。"

log "▶ 開始生圖（預計 3-5 分鐘）"
echo "$PROMPT" | codex exec --skip-git-repo-check --image "動作解析圖檔們/全部物件.png" 2>&1 | tail -20 >> "$LOG"

if [ -f "$OUT" ] && [ -s "$OUT" ]; then
  log "✓ 完成: $OUT ($(sips -g pixelWidth -g pixelHeight "$OUT" 2>/dev/null | grep pixel | tr '\n' ' '))"
else
  log "✗ 失敗"
  exit 1
fi
