#!/bin/bash
# 用 lcd_remaster_v1.png 當 ref，請 AI 移除所有角色 + 桌椅 + 掩體 + 物件，
# 只保留空場景（牆、地板、吧台、酒瓶架、海報、招牌、門），吧台檯面加深
set -u
cd "$(dirname "$0")/.."

LOG="scripts/gen_empty_bg.log"
OUT="public/assets/A/A00_empty_bg.png"
REF="public/assets/lcd_remaster_v1.png"
mkdir -p public/assets/A

ts() { date +"%H:%M:%S"; }
log() { echo "[$(ts)] $*" | tee -a "$LOG"; }

log "==== 生成空場景背景 ===="

PROMPT="附加圖是 lcd_remaster_v1.png — 一張 Pixar 3D 風格的西部酒吧 LCD 螢幕畫面。

任務：請用 image_gen 工具生成一張【1536×1024 PNG】，
就是把附加圖中所有【角色、桌椅、掩體、物件】用該位置的【牆面或地板紋理】填補蓋掉，
得到一張【完全相同視角、完全相同構圖、完全相同邊框、只是空無一人】的版本。

【絕對嚴格 — 必須 100% 沿用附加圖】：
✓ 相機角度：附加圖的【45° 斜俯視 top-down 視角】，不准改成正面、不准改成側面、不准拉近、不准拉遠
✓ 視野範圍：附加圖看得到的【後牆 + 左牆 + 木地板大片區域】通通要在
✓ 綠色 LCD 邊框：附加圖外圍的【綠色圓角邊框】必須完整保留
✓ 透視 / 比例 / zoom level 完全一致 — 想像就是把附加圖載入 Photoshop、用仿製圖章把角色和家具蓋掉
✓ 光線方向、色調、Pixar 3D 質感 100% 沿用

【必須保留 + 強化細節】：
✓ 後牆（米色木板牆）
✓ 木地板：【極為重要 — 整片地板的「木板間隔縫」必須全部【平行、方向一致】】，
   在 45° 斜俯視下：所有木板長邊與木板間的接縫線都【由近到遠、平行延伸】（朝畫面深處消失點走）。
   ✗ 不准出現有些縫橫向、有些縱向的混亂走向。
   ✗ 不准出現木板拼接圖案不規則或交錯的拼花。
   ✓ 整片地板就是【規律的長條木板，所有縫線完全平行】，像體育館或木質碼頭的長板地。
   高細節：每一條木板都有微妙的木紋肌理、結痕、磨損、上漆光澤、立體陰影。
✓ 【極度重要 — 吧台後方要有「酒保走道」】：
   後牆酒瓶架【不直接貼到】吧台頂面，兩者之間必須有一條【看得到木地板的走道帶】，
   寬度約畫面高度 8-12%，這是酒保站立和走動的位置。
   完整垂直結構（從上到下）：
   ┌──────────────────────────────┐
   │ Y= 0-22%  後牆 + 酒瓶架 + 海報/招牌      │
   │ Y=22-32%  【酒保走道】(木地板)            │ ← 必須有，且看得到地板
   │ Y=32-50%  吧台頂面（深棕水平桌板，俯視展開）│
   │ Y=50-58%  吧台前面板（垂直擋板）          │
   │ Y=58-100% 客人地板（玩家走道）            │
   └──────────────────────────────┘

✓ 吧台檯面【頂部水平面】必須清楚展開可見：
   從 45° 俯視角度，吧台像一張【攤平的長方形桌面】，
   頂面是一大片可見的水平木板深色桌面，能清楚放下杯子、酒瓶、盤子。
   檯面顏色：深核桃木 / 深咖啡色光澤面（polished hardwood）。
   ✗ 不准吧台直接貼到酒瓶架（中間沒走道）
   ✗ 不准只看到「直立的吧台正面板」一條細條
✓ 吧台後方的【酒瓶架】shelf（多層、空架子或極少酒瓶裝飾），深棕木質、有木紋
✓ 牆上的【WANTED 通緝海報】（紙張質感、釘子、撕邊）
✓ 牆上的【SALOON 招牌】（深紅色木板、金色花式邊框）
✓ 牆上其他靜態裝飾（黃銅油燈、木框風景畫）
✓ 整體 Pixar 3D 風格、軟陰影、暖色調光線、所有木質元素都要有高細節木紋

【必須移除（不准出現任何）】：
✗ 所有角色：警長、通緝犯、酒保、丈夫、妻子 — 一個人都不准有
✗ 所有桌子（中央圓桌、小桌、所有桌子）
✗ 所有椅子、凳子、木桶座椅
✗ 警長的躲藏掩體（倒立桌、木板、藏身物）
✗ 吧台上的物件：杯子、酒瓶、盤子、蘋果、菸灰缸
✗ 地上的物件：炸彈、子彈、飛行物、破碎物
✗ 飛行中的炸藥棒
✗ 角色身影 / 殘影 / 剪影
✗ 文字 / 編號 / 紅圈標記
✗ 【彈簧門 swing door 木製門板要移除】：不畫木門本體（彈簧門之後會以獨立 sprite 疊上）
   ✓ 但是【門洞開口 + 門框 + 透出去的室外景象（天空、沙漠、街景、山丘）必須保留】
   ✓ 左牆位置畫一個【拱形 / 矩形門框開口】，洞裡透出明亮的西部小鎮街景（藍天、遠山、對面店舖剪影）
   ✓ 想像彈簧門整個被拆掉了，只剩門洞，看穿到外面

【目標】：生出來的圖就是一間【空無一人、桌椅全清空、吧台檯面光亮深色】的酒吧內景，
就像清晨剛打掃完還沒開門營業的樣子，畫面中央地板大片空白可以走人。

【輸出規範】：
- 1536×1024 PNG
- 整張就是 LCD 螢幕畫面內容，不要邊框、機殼、按鈕
- 保留與附加圖完全相同的相機視角和透視

完成後存到 /Users/batman_work/claude/apps/westernBar/$OUT
並用 sips 確認 1536×1024。"

log "▶ 開始生圖（預計 3-5 分鐘）"
echo "$PROMPT" | codex exec --skip-git-repo-check --image "$REF" 2>&1 | tail -20 >> "$LOG"

if [ -f "$OUT" ] && [ -s "$OUT" ]; then
  log "✓ 完成: $OUT"
  sips -g pixelWidth -g pixelHeight "$OUT" 2>/dev/null | grep pixel | tee -a "$LOG"
else
  log "✗ 失敗"
  exit 1
fi
